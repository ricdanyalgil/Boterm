const check = (condition, message) => { if (!condition) throw new Error(message); };
const tick = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
const grid = document.getElementById('terminal'), mosaicButton = document.getElementById('mosaic');
const original = sessions.get(activeID), project = activeWorkspace;
check(document.getElementById('split').nextElementSibling === mosaicButton, 'Mosaic must be beside Split');
mosaicButton.click();
check(sessions.size === 1 && !original.host.hidden, 'Mosaic must not create terminals');
for (let i = 2; i <= 8; i++) createSession(`Terminal ${i}`);
const peers = [...sessions.values()];
const other = createSession('Outro projeto', privateWorkspace);
activateSession(original.id);
await tick();
check(peers.every(s => !s.host.hidden) && other !== original.id && sessions.get(other).host.hidden, 'Mosaic must show only this project');
check(mosaicButton.getAttribute('aria-pressed') === 'true', 'Mosaic pressed state missing');
const selected = activeID;
activateSession(peers[3].id);
check(peers.every(s => !s.host.hidden), 'Selecting a terminal must preserve the mosaic');
check(peers[3].host.classList.contains('active'), 'Selected mosaic terminal must be highlighted');
const columns = [];
for (const width of [300, 700, 1200]) {
  grid.style.width = `${width}px`; fitVisible(); await tick();
  const rects = peers.map(s => s.host.getBoundingClientRect());
  columns.push(new Set(rects.map(r => Math.round(r.left))).size);
  check(rects.every(r => r.width > 0 && r.height > 0), 'Mosaic lost a terminal');
  check(new Set(rects.map(r => `${r.left},${r.top}`)).size === 8, 'Mosaic terminals overlap');
}
grid.style.width = ''; fitVisible(); await tick();
check(columns[0] === 1 && columns[1] > 1 && columns[2] > columns[1], 'Columns must adapt to available width');
check(getComputedStyle(peers[0].host.querySelector('.resize-vertical')).display === 'none', 'Automatic mosaic must hide manual split handles');
mosaicButton.click();
check(peers.filter(s => !s.host.hidden).length === 1 && !peers[3].host.hidden, 'Leaving mosaic must preserve the active terminal');
document.getElementById('split').click();
check(split && !mosaic && mosaicButton.getAttribute('aria-pressed') === 'false', 'Split transition failed');
mosaicButton.click();
check(mosaic && !split && document.getElementById('split').getAttribute('aria-pressed') === 'false', 'Mosaic transition failed');
check(peers.every(s => sessions.get(s.id) === s && s.workspace === project), 'Layout must preserve terminal instances');
activateSession(selected);
await tick();
return {mosaic: true, terminals: 8, projectIsolation: true, activeTerminalPreserved: true, responsiveColumns: columns, splitTransition: true, terminalInstancesPreserved: true};
