const check = (condition, message) => { if (!condition) throw new Error(message); };
const tick = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
const original = sessions.get(activeID), workspace = activeWorkspace;
const peer = sessions.get(createSession('Engenharia de loop'));
const unrelated = sessions.get(createSession('Outro terminal'));
const privatePeer = sessions.get(createSession('Privado', privateWorkspace));
activateSession(original.id);
for (let i = 0; i < 100 && !screenText(peer.term).trim(); i++) await new Promise(resolve => setTimeout(resolve, 100));
check(screenText(peer.term).trim(), 'Peer shell did not start');
const chat = s => s.host.querySelector('.session-conversation');
const rows = s => [...chat(s).querySelectorAll('.conversation-message')];
const first = {id:'conversation-test-1',workspace,from:original.id,to:peer.id,fromName:original.name,toName:peer.name,time:new Date().toISOString(),text:'Revise a integração <img src=x onerror="window.BAD_MESSAGE=true">'};
showMessage(first);
check(rows(original).length === 1 && rows(peer).length === 1, 'Message must appear in both terminals');
check(!document.getElementById('team-log') && !document.getElementById('team-form').querySelector('.conversation-message'), 'Global composer must not duplicate the conversation');
check(chat(original).querySelector('[role="log"]').getAttribute('aria-live') === 'polite' && chat(peer).querySelector('[role="log"]').getAttribute('aria-live') === 'off', 'Only the active conversation should announce messages');
check(chat(unrelated).hidden && chat(privatePeer).hidden, 'Conversation leaked into another terminal/project');
check(!chat(original).querySelector('img') && !window.BAD_MESSAGE, 'Message text became executable HTML');
const firstRow = rows(original)[0];
check(firstRow.style.color && firstRow.style.color === rows(peer)[0].style.color && messageHistory.find(m => m.id === first.id).color === original.color, 'Speaker color missing');
showMessage({...first,id:'conversation-test-2',from:peer.id,to:original.id,fromName:peer.name,toName:original.name,text:'Revisão concluída. A integração está correta.'});
check(rows(original).length === 2 && rows(peer).length === 2, 'Reply must appear in both terminals');
check(rows(original)[0] === firstRow, 'New messages must preserve existing rows');
check(rows(original)[1].style.color !== firstRow.style.color, 'Speakers must have different colors');
showMessage({...first,id:'conversation-test-3',to:'*',toName:'Equipe',text:'Integração pronta para a próxima etapa.'});
check(rows(unrelated).length === 1 && chat(privatePeer).hidden, 'Broadcast must stay within the project');
renameSession(peer.id,'Engenharia de loop · revisão');
check(chat(peer).querySelector('[role="log"]').getAttribute('aria-label').includes('revisão'), 'Conversation accessible name is stale');
await new Promise(resolve => peer.term.write('\x1b[2J\x1b[HAllow access to this file?\r\n> 1. Yes, allow access\r\n  2. No, deny access\r\nEsc to cancel',resolve));
await tick();
check(peer.attention === 'Confirmação solicitada' && peer.host.classList.contains('needs-attention'), 'Permission prompt must request attention');
const peerRow = [...document.querySelectorAll('#sessions button')].find(row => row.getAttribute('aria-label')?.startsWith(peer.name));
check(peerRow?.classList.contains('needs-attention') && peerRow.textContent.includes('Confirmação solicitada'), 'Sidebar attention indicator missing');
peer.term.reset(); await new Promise(resolve => peer.term.write('Operação concluída.\r\n› Ask Codex to do anything',resolve));
await tick();
check(!peer.attention && !peer.host.classList.contains('needs-attention'), 'Attention did not clear after the prompt');
await new Promise(resolve => peer.term.write('\x1b[2J\x1b[HRun this command?\r\n> 1. Yes, run command\r\n  4. No, cancel',resolve));
await tick();
document.getElementById('mosaic').click();
await tick();
return {mirroredConversation:true,speakerColors:true,projectIsolation:true,literalText:true,rowsPreserved:true,permissionAttention:true,attentionClears:true,mosaic:true};
